    '- 主错误类型互斥：到达目标后继续走优先列为停止错误，非边属性另存；本次所有失败轨迹的边均真实合法，无预算截断或被审计器中止。','',
    '|错误类型|简单图，1091查询|困难图，555查询|','|---|---:|---:|',
