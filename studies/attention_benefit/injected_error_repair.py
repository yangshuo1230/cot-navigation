"""Controlled clean/error state prefixes, autonomous continuation to answer.

The action token (including MISTAKE) and all later tokens are generated by
the model. Native 4K budget and batch16, no oracle repair or forced marker.
"""
import argparse,os,runpy,time,hashlib
from pathlib import Path
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--domain',required=True,choices=['main','hard','deep'])
parser.add_argument('--arms',nargs='+',default=['clean','error'],choices=['clean','error'])
parser.add_argument('--gpu',type=int,required=True)
args=parser.parse_args()
os.environ['CUDA_VISIBLE_DEVICES']=str(args.gpu);os.environ['WANDB_MODE']='disabled'
os.environ.setdefault('OMP_NUM_THREADS','2')
P=Path(__file__).resolve().parent;C=runpy.run_path(str(P/'injected_error_common.py'))
import numpy as np
import torch


def recovery(body,source,target,adj,tok,event_record):
    """True state replay; printed fields never mutate the real search state.

After an illegal action the state is undefined and recovery is not scored
as successful. A MISTAKE cancels a record without advancing true state.
"""
    stack=[source];visited={source};begin=0;record=-1;valid=True;terminal=False
    detected=False;first_later=None;explicit=False
    for end,t in enumerate(body):
        if t!=tok.id(';'):continue
        record+=1;parts=[[]]
        for value in body[begin:end]:
            if value==tok.id('|'):parts.append([])
            else:parts[-1].append(value)
        begin=end+1
        if not valid or terminal or len(parts)!=4 or not stack:valid=False;continue
        frontier,shown_visited,candidates,action=parts;cur=stack[-1]
        eligible=set(adj.get(cur,[]))-visited
        fields=(frontier==stack and len(shown_visited)==len(set(shown_visited)) and set(shown_visited)==visited
                and len(candidates)==len(set(candidates)) and set(candidates)==eligible)
        if action==[tok.stoi.get('<MISTAKE>',-1)]:
            if record==event_record:detected=True
            continue
        wanted='<FOUND>' if cur==target else '<PUSH>' if eligible else '<POP>' if len(stack)>1 else '<EXHAUST>'
        legal=(len(action)==(2 if wanted=='<PUSH>' else 1) and bool(action) and action[0]==tok.id(wanted))
        if legal and wanted=='<PUSH>':legal=action[1] in eligible
        priority=wanted!='<PUSH>' or bool(candidates) and len(action)>1 and action[1]==candidates[0]
        if record>event_record and first_later is None:
            first_later=bool(fields and legal and priority)
            explicit=detected and first_later
        if not legal:valid=False;continue
        if wanted=='<PUSH>':stack.append(action[1]);visited.add(action[1])
        elif wanted=='<POP>':stack.pop()
        else:terminal=True
    return dict(detected=detected,next_record_correct=bool(first_later),explicit_repair=bool(explicit))


def main():
    torch.set_num_threads(2);torch.cuda.set_per_process_memory_fraction(.15)
    data=C['Data'](args.domain);events,sampling=C['repair_events'](data)
    assert events
    for arm in args.arms:
        dest=C['OUT']/f'repair_{args.domain}_{arm}.json'
        if dest.exists() and __import__('json').loads(dest.read_text()).get('finished'):continue
        cfg,tok,model,meta=C['load_model'](arm,'cuda')
        assert tok.itos[:len(data.tok)]==data.tok.itos
        records=[];examples=[];start=time.time()
        inputs=[]
        for ei,e in enumerate(events):
            for label,prompt in enumerate(data.action_pair(e)):inputs.append((ei,label,e,prompt))
        for offset in range(0,len(inputs),16):
            batch=inputs[offset:offset+16]
            with torch.no_grad():
                outputs=C['D']['generate'](model,[r[3] for r in batch],cfg.protocol.name,tok,cfg.train.precision,
                    max_new_tokens=0,cot_margin=cfg.protocol.cot_margin)
            for (ei,label,e,prompt),g in zip(batch,outputs):
                ref=data.row(e);q=e['query'];nodes=data.source.node_vocab_ids(q,tok)
                raw=data.source.adj(q);adj={nodes[u]:[nodes[v] for v in vs] for u,vs in enumerate(raw)}
                source=nodes[int(data.source.arrays['s_topo'][q])];target=nodes[int(data.source.arrays['t_topo'][q])]
                body=prompt[ref.prompt_len:]+g['trace_tokens']
                audit=C['D']['audit'](body,g['pred'],adj,source,target,tok,False)
                recovered=recovery(body,source,target,adj,tok,e['record'])
                row=dict(event=ei,query_id=q,kind=e['kind'],field=e['field'],condition='error' if label else 'clean',
                    label=e['label'],pred=g['pred'],correct=not g['format_fail'] and g['pred']==e['label'],
                    interrupted=g['cot_interrupted'],forced_stop=g['forced_stop'],trace_length=len(g['trace_tokens']),
                    effective_complete=audit['effective_complete'],execution_complete=audit['execution_complete'],
                    first_error=audit['first_error'],raw_mistake_tokens=g['trace_tokens'].count(tok.stoi.get('<MISTAKE>',-1)),
                    **recovered)
                records.append(row)
                if label and len(examples)<6 and (recovered['explicit_repair'] or not row['correct']):
                    examples.append(dict(query_id=q,kind=e['kind'],correct=row['correct'],**recovered,
                        input_tail=tok.decode(prompt[-70:]),generated_begin=tok.decode(g['generated'][:100])))
            C['write'](dest,dict(finished=len(records)==len(inputs),domain=args.domain,arm=arm,metadata=meta,
                sampling=sampling,n_pairs=len(events),batch_size=16,navigation_input='canonical legal history plus clean/corrupt current state, before action',
                n_done=len(records),rows=records,examples=examples,seconds=time.time()-start))
            print('REPAIR',args.domain,arm,len(records),'/',len(inputs),round(time.time()-start,1),flush=True)
        del model;torch.cuda.empty_cache()


if __name__=='__main__':main()
